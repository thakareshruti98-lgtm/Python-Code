# Practical 10: Stack and Queue Operations

# Stack Operations
stack = []

stack.append("Task 1")
stack.append("Task 2")
stack.append("Task 3")

print("Stack:", stack)

print("Popped Task:", stack.pop())
print("Stack after pop:", stack)


# Queue Operations
queue = []

queue.append("Task 1")
queue.append("Task 2")
queue.append("Task 3")

print("\nQueue:", queue)

print("Removed Task:", queue.pop(0))
print("Queue after deletion:", queue)